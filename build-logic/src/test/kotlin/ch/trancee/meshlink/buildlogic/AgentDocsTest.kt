class AgentDocsTest {
    @get:Rule val temporaryFolder = TemporaryFolder()

    @Test
    fun updateWritesTheDocumentIndex() {
        // Arrange
        val root = repository()

        // Act
        task(root, update = true).run()

        // Assert
        assertEquals(INDEX, root.resolve("docs/agents/index.md").readText())
    }

    @Test
    fun updateWritesTheAdrIndex() {
        // Arrange
        val root = repository()

        // Act
        task(root, update = true).run()

        // Assert
        assertEquals(ADRS, root.resolve("docs/adr/README.md").readText())
    }

    @Test
    fun updateWritesOneContractLinePerDeclaration() {
        // Arrange
        val root = repository()

        // Act
        task(root, update = true).run()

        // Assert
        assertEquals(CONTRACT, root.resolve("docs/agents/contract.md").readText())
    }

    @Test
    fun checkPassesAfterAnUpdate() {
        // Arrange
        val root = repository()
        task(root, update = true).run()

        // Act
        task(root, update = false).run()

        // Assert: no exception.
    }

    @Test
    fun stalePageAndMissingPageFailTheCheckByName() {
        // Arrange
        val root = repository()
        task(root, update = true).run()
        root
            .resolve("docs/adr/0002-second.md")
            .writeText("# 0002: Second decision\n\nStatus: superseded by 0001 (2026-11-01). Version: 2 (amended).\n")
        root.resolve("docs/agents/contract.md").delete()

        // Act
        val failure = assertFailsWith<GradleException> { task(root, update = false).run() }

        // Assert
        assertEquals(
            "Generated agent docs are stale (ADR 0006 decision 4): run ./gradlew updateReference\n" +
                "docs/adr/README.md\ndocs/agents/contract.md",
            failure.message,
        )
    }

    @Test
    fun documentInAnUnknownDirectoryFails() {
        // Arrange
        val root = repository()
        root.resolve("docs/notes").mkdirs()
        root.resolve("docs/notes/idea.md").writeText("# Idea\n")

        // Act
        val failure = assertFailsWith<GradleException> { task(root, update = true).run() }

        // Assert
        assertEquals("docs/notes/idea.md has no document type: add its directory to AgentDocs", failure.message)
    }

    private fun repository(): File {
        val root = temporaryFolder.newFolder()
        mapOf(
            "AGENTS.md" to "# AGENTS\n",
            "CONSTITUTION.md" to "# Constitution\n",
            "docs/README.md" to "# MeshLink documentation\n",
            "docs/adr/0001-first.md" to
                "# 0001: First decision\n\nStatus: accepted (2026-10-31; ticket). Version: 2 (amended 2026-11-02, x).\n",
            "docs/adr/0002-second.md" to "# 0002: Second decision\n\nStatus: superseded by 0001 (2026-11-01). Version: 1.\n",
            "docs/spec/link.md" to "# Link layer\n",
            "docs/research/2026-10-31-x.md" to "# Research: options\n",
            "docs/reference/diagnostics.md" to
                "# Diagnostics\n\n<!-- Generated by DiagnosticReferenceTest from the Kotlin source. -->\n",
            "docs/evidence/run/summary.md" to "| a | b |\n|---|---|\n",
            "docs/how-to/fix-it.md" to "Intro.\n\n## Fix | it\n",
            "meshlink/api/meshlink.klib.api" to DUMP,
            "meshlink-testing/api/meshlink-testing.klib.api" to
                "// Klib ABI Dump\n// Library unique name: <ch.trancee.meshlink:meshlink-testing>\n",
        ).forEach { (path, text) -> root.resolve(path).apply { parentFile.mkdirs() }.writeText(text) }
        return root
    }

    private fun task(
        root: File,
        update: Boolean,
    ): AgentDocsTask {
        val project = ProjectBuilder.builder().withProjectDir(root).build()
        return project.tasks
            .register("docs", AgentDocsTask::class.java) {
                AgentDocs.configure(this, project)
                this.update.set(update)
            }.get()
    }

