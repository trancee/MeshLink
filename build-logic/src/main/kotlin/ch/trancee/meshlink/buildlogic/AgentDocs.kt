package ch.trancee.meshlink.buildlogic

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.Project
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.Internal
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import org.gradle.work.DisableCachingByDefault
import java.io.File

/**
 * ADR 0006 decisions 4 and 9: the generated agent layer. `docs/agents/index.md` lists every document with its type,
 * authority and status; `docs/agents/contract.md` summarizes the klib ABI dumps one line per declaration; and
 * `docs/adr/README.md` lists the ADRs from their headers.
 */
internal object AgentDocs {
    const val INDEX = "docs/agents/index.md"
    const val CONTRACT = "docs/agents/contract.md"
    const val ADRS = "docs/adr/README.md"

    /** The root files the index lists beside `docs/`. */
    private val ROOT_FILES =
        mapOf(
            "AGENTS.md" to "governance",
            "CHANGELOG.md" to "changelog",
            "CONSTITUTION.md" to "governance",
            "GLOSSARY.md" to "glossary",
            "KOTLIN.md" to "governance",
            "PROJECT.md" to "governance",
            "README.md" to "navigation",
            "SECURITY.md" to "governance",
        )

    /** The document type of each `docs/` directory. */
    private val DIRECTORIES =
        mapOf(
            "adr" to "adr",
            "agents" to "agents",
            "evidence" to "evidence",
            "explanation" to "explanation",
            "how-to" to "how-to",
            "reference" to "reference",
            "research" to "research",
            "spec" to "spec",
            "tutorials" to "tutorial",
        )

    private const val COMMENT = "<!-- Generated by AgentDocs (build-logic): run ./gradlew updateReference. -->"
    private const val GENERATED = "<!-- Generated by"
    private const val INDEX_TITLE = "Documentation index"
    private const val CONTRACT_TITLE = "Contract reference"
    private const val ADRS_TITLE = "Architecture decision records"

    private val ADR = Regex("""^docs/adr/\d{4}-.*\.md$""")
    private val HEADING = Regex("""^#{1,6} (.+)$""", RegexOption.MULTILINE)
    private val STATUS = Regex("""^Status: (.+?)(?: \(|\.|$)""", RegexOption.MULTILINE)
    private val VERSION = Regex("""Version: (\d+)""")
    private val LIBRARY = Regex("""^// Library unique name: <[^:>]+:([^>]+)>""", RegexOption.MULTILINE)
    private val KIND =
        Regex("""\b(fun interface|enum entry|constructor|annotation class|enum class|interface|class|object|fun|val|var)\b""")
    private val COMPONENT = Regex("""component\d+""")
    private val ANY_MEMBERS = setOf("copy", "equals", "hashCode", "toString")
    private val ENUM_MEMBERS = setOf("entries", "values", "valueOf")

    fun configure(
        task: AgentDocsTask,
        project: Project,
    ) {
        val root = project.layout.projectDirectory
        task.root.set(root)
        task.documents.from(project.fileTree(root.dir("docs")) { include("**/*.md") })
        task.documents.from(ROOT_FILES.keys.map(root::file).filter { it.asFile.exists() })
        task.dumps.from(project.fileTree(root) { include("*/api/*.klib.api") })
    }

    /** Each generated page by its path relative to [root], from the [documents] and the klib [dumps]. */
    fun pages(
        root: File,
        documents: Set<File>,
        dumps: Set<File>,
    ): Map<String, String> {
        val texts = documents.associate { it.relativeTo(root).invariantSeparatorsPath to it.readText() }
        val adrs = adrIndex(texts)
        val contract = contract(dumps.map(File::readText))
        val generated = mapOf(INDEX to "# $INDEX_TITLE\n", CONTRACT to contract, ADRS to adrs)
        return generated + (INDEX to index(texts + generated))
    }

    private fun index(texts: Map<String, String>): String {
        val rows =
            texts.keys.sorted().joinToString("") { path ->
                val text = texts.getValue(path)
                val type = type(path)
                val generated = text.contains(GENERATED) || path == INDEX
                val authority =
                    when {
                        path == "CONSTITUTION.md" -> "1"
                        type == "spec" -> "2"
                        type == "adr" -> "4"
                        generated -> "5"
                        type == "research" -> "none"
                        else -> "6"
                    }
                val status =
                    when {
                        type == "adr" -> status(path, text)
                        generated -> "generated"
                        else -> "current"
                    }
                val link = File(path).relativeTo(File("docs/agents")).invariantSeparatorsPath
                "| [`$path`]($link) | ${title(path, text).replace("|", "\\|")} | $type | $authority | $status |\n"
            }
        return page(
            INDEX_TITLE,
            "Every document with its type, its authority and its status. When two documents disagree, the lower " +
                "authority number wins (ADR 0006 decision 2): 1 Constitution, 2 protocol spec and vectors, 3 public API " +
                "dump, 4 ADRs, 5 generated reference, 6 everything else. Research is dated and never authoritative.\n\n" +
                "| Document | Title | Type | Authority | Status |\n|---|---|---|---|---|\n" + rows,
        )
    }

    private fun adrIndex(texts: Map<String, String>): String {
        val rows =
            texts.keys.filter(ADR::matches).sorted().joinToString("") { path ->
                val text = texts.getValue(path)
                val name = path.substringAfterLast('/')
                val version = VERSION.find(text)?.groupValues?.get(1) ?: throw GradleException("$path has no Version")
                "| [${name.take(4)}]($name) | ${title(path, text).substringAfter(": ")} | ${status(path, text)} | $version |\n"
            }
        return page(
            ADRS_TITLE,
            "Each hard decision with its alternatives and risks, in one numbered list (ADR 0006 decision 9). A replaced " +
                "ADR is never deleted; its status names the ADR that supersedes it. The version is 1 plus the number of " +
                "amendments, which `tools/check_adrs.py` checks.\n\n" +
                "| ADR | Title | Status | Version |\n|---|---|---|---|\n" + rows,
        )
    }

    private fun contract(dumps: List<String>): String {
        val modules =
            dumps
                .associateBy { LIBRARY.find(it)?.groupValues?.get(1) ?: throw GradleException("A klib dump has no library name") }
                .toSortedMap()
                .map { (module, dump) ->
                    val (internal, public) = declarations(dump).partition { it.internal }
                    val sections =
                        if (public.isEmpty() && internal.isEmpty()) {
                            "No public declarations.\n"
                        } else {
                            "### Public API\n\n${table(public)}" +
                                if (internal.isEmpty()) {
                                    ""
                                } else {
                                    "\n### Internal API\n\nDeclarations in `ch.trancee.meshlink.internal`: public only so " +
                                        "MeshLink's own modules can reach them. Apps don't use them.\n\n${table(internal)}"
                                }
                        }
                    "## $module\n\n$sections"
                }
        return page(
            CONTRACT_TITLE,
            "One line per public declaration of each published module, from its committed klib ABI dump " +
                "(`<module>/api/<module>.klib.api`). The dump is the contract (ADR 0006 decision 2); this page is its " +
                "summary for reading and search. Property types come from their getters. Members the compiler generates " +
                "are left out: enum `entries`, `values` and `valueOf`, and `componentN`, `copy`, `equals`, `hashCode` " +
                "and `toString`.\n\n" + modules.joinToString("\n"),
        )
    }

    private class Declaration(
        val kind: String,
        var signature: String,
        val internal: Boolean,
    )

    /** The declarations of a klib dump in its order, each with its fully qualified name in its signature. */
    private fun declarations(dump: String): List<Declaration> {
        val declarations = mutableListOf<Declaration>()
        val properties = mutableMapOf<String, Declaration>()
        dump.lines().map(String::trim).filter { !it.startsWith("//") && it.contains(" // ") }.forEach { line ->
            val text = line.substringBefore(" // ").removeSuffix("{").trim()
            val name = line.substringAfter(" // ").substringBefore("|")
            val simple = name.substringAfterLast('/').substringAfterLast('.')
            val static = line.substringAfter("|").contains("#static")
            when {
                simple.startsWith("<get-") -> {
                    properties[name.substringBeforeLast('.')]?.let { it.signature += ": " + text.substringAfter("): ") }
                }

                simple.startsWith("<set-") || simple in ANY_MEMBERS || COMPONENT.matches(simple) ||
                    (static && simple in ENUM_MEMBERS) -> {
                    Unit
                }

                else -> {
                    val signature =
                        when {
                            text.contains(name) -> {
                                text
                            }

                            simple == "<init>" -> {
                                text.replace("<init>", name.substringBeforeLast('.'))
                            }

                            else -> {
                                Regex(
                                    """(?<=\s|\)\.)${Regex.escape(simple)}(?=[\s(<:]|$)""",
                                ).replaceFirst(text, Regex.escapeReplacement(name))
                            }
                        }
                    val kind = KIND.find(text)?.value ?: throw GradleException("Unknown declaration kind: $text")
                    val internal = "internal" in name.substringBefore('/').split('.')
                    val declaration = Declaration(kind, signature, internal)
                    declarations += declaration
                    if (kind == "val" || kind == "var") properties[name] = declaration
                }
            }
        }
        return declarations
    }

    private fun table(declarations: List<Declaration>) =
        "| Kind | Declaration |\n|---|---|\n" + declarations.joinToString("") { "| ${it.kind} | `${it.signature}` |\n" }

    private fun page(
        title: String,
        body: String,
    ) = "# $title\n\n$COMMENT\n\n$body"

    private fun type(path: String): String =
        ROOT_FILES[path] ?: when (path) {
            "docs/README.md", ADRS -> "navigation"
            else -> DIRECTORIES[path.split('/')[1]]
        } ?: throw GradleException("$path has no document type: add its directory to AgentDocs")

    private fun title(
        path: String,
        text: String,
    ) = HEADING
        .find(text)
        ?.groupValues
        ?.get(1)
        ?.trim() ?: path.substringAfterLast('/')

    private fun status(
        path: String,
        text: String,
    ) = STATUS.find(text)?.groupValues?.get(1) ?: throw GradleException("$path has no Status line")
}

/** Writes the generated agent pages when [update] is set; otherwise fails naming each committed page that differs. */
@DisableCachingByDefault(because = "Reads a few text files; nothing to cache.")
abstract class AgentDocsTask : DefaultTask() {
    @get:Input abstract val update: Property<Boolean>

    @get:Internal abstract val root: DirectoryProperty

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val documents: ConfigurableFileCollection

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val dumps: ConfigurableFileCollection

    @TaskAction
    fun run() {
        val base = root.get().asFile
        val pages = AgentDocs.pages(base, documents.files, dumps.files)
        if (update.get()) {
            pages.forEach { (path, text) -> base.resolve(path).apply { parentFile.mkdirs() }.writeText(text) }
        } else {
            val stale = pages.filter { (path, text) -> base.resolve(path).let { !it.exists() || it.readText() != text } }.keys.sorted()
            if (stale.isNotEmpty()) {
                throw GradleException(
                    "Generated agent docs are stale (ADR 0006 decision 4): run ./gradlew updateReference\n${stale.joinToString("\n")}",
                )
            }
        }
    }
}
