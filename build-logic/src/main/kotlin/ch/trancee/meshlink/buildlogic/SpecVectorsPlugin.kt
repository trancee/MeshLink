package ch.trancee.meshlink.buildlogic

import groovy.json.JsonSlurper
import org.gradle.api.DefaultTask
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import org.jetbrains.kotlin.gradle.dsl.KotlinMultiplatformExtension

/**
 * Makes the protocol test vectors in `docs/spec/vectors/` available to `commonTest`, so one vector
 * runner serves the Android host and the iOS simulator without file access at test time.
 *
 * `generateDerivationVectors` turns `derivations.json` into Kotlin source: one `DerivationVector` per
 * test, with every input as a string (hex or decimal, as in the file).
 */
class SpecVectorsPlugin : Plugin<Project> {
    override fun apply(project: Project) {
        val generate =
            project.tasks.register("generateDerivationVectors", GenerateDerivationVectors::class.java) {
                group = "verification"
                description = "Generates commonTest Kotlin source from docs/spec/vectors/derivations.json."
                vectors.set(
                    project.rootProject.layout.projectDirectory
                        .file("docs/spec/vectors/derivations.json"),
                )
                outputDirectory.set(project.layout.buildDirectory.dir("generated/meshlink/vectors/commonTest/kotlin"))
            }
        project.pluginManager.withPlugin("org.jetbrains.kotlin.multiplatform") {
            project.extensions.configure(KotlinMultiplatformExtension::class.java) {
                sourceSets.named("commonTest") { kotlin.srcDir(generate.flatMap { it.outputDirectory }) }
            }
        }
    }
}

/** Writes `DerivationVectors.kt` from a Wycheproof-style derivation vector file. */
@CacheableTask
abstract class GenerateDerivationVectors : DefaultTask() {
    /** The `derivations.json` file. */
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val vectors: RegularFileProperty

    /** The Kotlin source root the generated file goes in. */
    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val root = JsonSlurper().parse(vectors.get().asFile) as Map<*, *>
        val lines =
            (root["testGroups"] as List<*>).flatMap { group ->
                group as Map<*, *>
                val derivation = group["derivation"] as String
                (group["tests"] as List<*>).map { test ->
                    test as Map<*, *>
                    val inputs =
                        (test["inputs"] as Map<*, *>).entries.joinToString(", ") { (name, value) ->
                            "${literal(name.toString())} to ${literal(value.toString())}"
                        }
                    "        DerivationVector(${literal(derivation)}, ${test["tcId"]}, mapOf($inputs), " +
                        "${literal(test["output"].toString())}),"
                }
            }
        val file = outputDirectory.get().file("ch/trancee/meshlink/vectors/DerivationVectors.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            buildString {
                appendLine("// Generated by generateDerivationVectors from docs/spec/vectors/derivations.json.")
                appendLine("// Do not edit; change the vector file and rebuild.")
                appendLine("package ch.trancee.meshlink.vectors")
                appendLine()
                appendLine("/** One derivation test: [inputs] as hex or decimal strings, [output] as hex. */")
                appendLine("internal data class DerivationVector(")
                appendLine("    val derivation: String,")
                appendLine("    val tcId: Int,")
                appendLine("    val inputs: Map<String, String>,")
                appendLine("    val output: String,")
                appendLine(")")
                appendLine()
                appendLine("/** Every test in derivations.json, in file order. */")
                appendLine("internal val derivationVectors: List<DerivationVector> =")
                appendLine("    listOf(")
                lines.forEach(::appendLine)
                appendLine("    )")
            },
        )
    }

    private fun literal(value: String): String {
        require(value.all { it in ' '..'~' && it != '"' && it != '\\' && it != '$' }) {
            "vector strings must be printable ASCII without quotes, backslashes or dollar signs: $value"
        }
        return "\"$value\""
    }
}
