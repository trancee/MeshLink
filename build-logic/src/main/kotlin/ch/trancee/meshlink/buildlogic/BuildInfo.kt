package ch.trancee.meshlink.buildlogic

import org.gradle.api.DefaultTask
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction
import org.jetbrains.kotlin.gradle.dsl.KotlinMultiplatformExtension

/** Writes `ch.trancee.meshlink.internal.BuildInfo`, an internal object holding the library version. */
@CacheableTask
abstract class GenerateBuildInfo : DefaultTask() {
    @get:Input
    abstract val version: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val file = outputDirectory.file("ch/trancee/meshlink/internal/BuildInfo.kt").get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by the generateBuildInfo task from the root meshlink.version property. Do not edit.
            |package ch.trancee.meshlink.internal
            |
            |internal object BuildInfo {
            |    const val VERSION: String = "${version.get()}"
            |}
            |
            """.trimMargin(),
        )
    }
}

/**
 * Adds the generated `BuildInfo` object to the module's `commonMain` source set. Its version is the same
 * `meshlink.version` that every published artifact carries (ADR 0019 decision 1). Apply after a MeshLink
 * KMP plugin.
 */
class BuildInfoPlugin : Plugin<Project> {
    override fun apply(project: Project) = project.generateBuildInfo()
}

private fun Project.generateBuildInfo() {
    val task =
        tasks.register("generateBuildInfo", GenerateBuildInfo::class.java) {
            version.set(meshLinkVersion())
            outputDirectory.set(layout.buildDirectory.dir("generated/buildInfo/commonMain/kotlin"))
        }
    extensions.configure(KotlinMultiplatformExtension::class.java) {
        sourceSets.getByName("commonMain").kotlin.srcDir(task.flatMap { it.outputDirectory })
    }
}
