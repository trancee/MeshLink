package ch.trancee.meshlink

import java.io.File
import kotlin.test.assertEquals

/**
 * What the reference tests share (ADR 0006 decision 3): the repository, the KDoc of the Kotlin source as
 * Markdown, and the check that a committed page matches the page generated from the source.
 */
internal object ReferencePages {
    val root = File(checkNotNull(System.getProperty("reference.root")) { "reference.root is not set" })
    val sources = File(root, "meshlink/src/commonMain/kotlin/ch/trancee/meshlink")

    // A KDoc block, its text in group 1.
    private const val KDOC = """/\*\*((?:(?!\*/).)*)\*/\s*"""

    private val SYMBOL = Regex("""\[([A-Za-z_][\w.]*)\](?!\()""")

    /** The comment that opens a page [test] generates. */
    fun generated(test: String): String =
        "<!-- Generated by $test from the Kotlin source: edit the KDoc, then run ./gradlew updateReference. -->"

    /**
     * Fails when the committed file at [path], relative to the repository, differs from [generated];
     * `./gradlew updateReference` writes [generated] there first.
     */
    fun compare(
        path: String,
        generated: String,
    ) {
        val page = File(root, path)
        if (System.getProperty("reference.update") == "true") page.writeText(generated)
        val committed = if (page.exists()) page.readText() else ""
        assertEquals(generated, committed, "$path is stale: run ./gradlew updateReference")
    }

    /** A KDoc block directly before [declaration], its text in group 1. */
    fun documented(declaration: String) = Regex(KDOC + declaration, RegexOption.DOT_MATCHES_ALL)

    /** [text] with each `[Symbol]` written as code. */
    fun symbols(text: String): String = SYMBOL.replace(text, "`$1`")

    /** KDoc body to Markdown: drops the leading stars, joins wrapped lines and writes `[Symbol]` as code. */
    fun markdown(kdoc: String): String {
        val lines = kdoc.lines().map { it.trim().removePrefix("*").removePrefix(" ") }.dropWhile { it.isBlank() }
        val blocks = mutableListOf<MutableList<String>>()
        var fenced = false
        var paragraph = true
        for (line in lines.dropLastWhile { it.isBlank() }) {
            when {
                line.startsWith("```") -> {
                    if (!fenced) blocks += mutableListOf<String>()
                    blocks.last() += line
                    fenced = !fenced
                    paragraph = false
                }

                fenced -> {
                    blocks.last() += line
                }

                line.isBlank() -> {
                    paragraph = false
                }

                paragraph && blocks.isNotEmpty() -> {
                    blocks.last()[0] += " $line"
                }

                else -> {
                    blocks += mutableListOf(line)
                    paragraph = true
                }
            }
        }
        return blocks.joinToString("\n\n") { block ->
            if (block[0].startsWith("```")) block.joinToString("\n") else symbols(block[0])
        }
    }
}
