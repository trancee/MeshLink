package ch.trancee.meshlink

import ch.trancee.meshlink.ReferencePages.compare
import ch.trancee.meshlink.ReferencePages.root
import org.junit.Test
import java.io.File
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

/**
 * Fills the code tables of the troubleshooting how-tos from each code's `Symptom` in the KDoc of
 * `DiagnosticEvent.kt` (ADR 0020 decision 8, ADR 0006 decision 6). The text around a table is written by
 * hand; the table between its markers is generated. It fails when a committed table differs;
 * `./gradlew updateReference` rewrites the tables.
 */
class TroubleshootingReferenceTest {
    private val catalog = DiagnosticCatalog.read()

    @Test
    fun everySymptomBelongsToATroubleshootingPage() {
        val known = PAGES.values.flatten() + NONE
        val unknown = catalog.events.filter { it.symptom.removeSuffix(".") !in known }.map { it.code }
        assertEquals(emptyList(), unknown, "codes whose symptom has no troubleshooting page")
    }

    @Test
    fun theTroubleshootingTablesMatchTheCatalog() =
        PAGES.forEach { (path, symptoms) ->
            val page = File(root, path)
            assertTrue(page.exists(), "$path is missing: write its guidance with an empty table for each symptom")
            compare(path, symptoms.fold(page.readText()) { text, symptom -> fill(path, text, symptom) })
        }

    // The page with the table for [symptom] between its markers regenerated.
    private fun fill(
        path: String,
        text: String,
        symptom: String,
    ): String {
        val begin = begin(symptom)
        assertEquals(1, text.split(begin).size - 1, "$path: one marker line $begin")
        val before = text.substringBefore(begin)
        val after = text.substringAfter(begin)
        assertTrue(END in after, "$path: $END after $begin")
        val codes = catalog.events.filter { it.symptom.removeSuffix(".") == symptom }
        codes.forEach { assertFalse('|' in it.cause, "${it.code}: a Cause with | breaks the table") }
        val rows =
            codes.map { event ->
                val cause = event.cause.replaceFirstChar { it.uppercase() }
                "| [${event.code}]($REFERENCE#${event.anchor}) | `${event.name}` | `${event.severity}` | $cause |"
            }
        val table = listOf("| Code | Event | Severity | Cause |", "|---|---|---|---|") + rows
        return before + begin + "\n\n" + table.joinToString("\n") + "\n\n" + END + after.substringAfter(END)
    }

    private companion object {
        const val NONE = "none"
        const val END = "<!-- END generated -->"
        const val REFERENCE = "../reference/diagnostics.md"

        // Each troubleshooting page and the symptoms whose codes it lists, in page order.
        val PAGES =
            mapOf(
                "docs/how-to/troubleshoot-peers-not-found.md" to listOf("peers not found"),
                "docs/how-to/troubleshoot-messages-not-delivered.md" to
                    listOf("messages not delivered", "messages delivered slowly"),
                "docs/how-to/troubleshoot-high-battery-use.md" to listOf("high battery use"),
            )

        fun begin(symptom: String): String =
            "<!-- BEGIN generated by TroubleshootingReferenceTest: codes whose symptom is \"$symptom\"; " +
                "edit the KDoc, then run ./gradlew updateReference. -->"
    }
}
