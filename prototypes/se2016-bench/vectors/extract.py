#!/usr/bin/env python3
"""Extracts X-Wing (draft-connolly-cfrg-xwing-kem-11 App. C) and HPKE (draft-ietf-hpke-pq-05 A.5) vectors
from the IETF text drafts into a Kotlin source file. Run: python3 vectors/extract.py (fetches the drafts)."""
import pathlib
import re
import urllib.request

HERE = pathlib.Path(__file__).parent
OUT = HERE.parent / "src/commonMain/kotlin/ch/trancee/meshlink/bench/crypto/Vectors.kt"
DRAFTS = {
    "xwing-11.txt": "https://www.ietf.org/archive/id/draft-connolly-cfrg-xwing-kem-11.txt",
    "hpke-pq-05.txt": "https://www.ietf.org/archive/id/draft-ietf-hpke-pq-05.txt",
}
PAGE_BREAK = re.compile(r"^(\S.*\[Page \d+\]|Internet-Draft .*|\f)$")


def lines(name):
    path = HERE / name
    if not path.exists():
        urllib.request.urlretrieve(DRAFTS[name], path)
    return [line for line in path.read_text().splitlines() if not PAGE_BREAK.match(line.strip() and line or "x")]


def fields(text_lines):
    """Parses 'label: hex' / 'label hex' blocks with hex continuation lines into (label, hex) pairs."""
    result = []
    for line in text_lines:
        stripped = line.strip()
        if not stripped or PAGE_BREAK.match(stripped):
            continue
        match = re.match(r"^([A-Za-z_]+):?\s+([0-9a-f]+)$", stripped)
        if match:
            result.append([match.group(1), match.group(2)])
        elif re.match(r"^[A-Za-z_]+:?$", stripped):
            result.append([stripped.rstrip(":"), ""])
        elif re.match(r"^[0-9a-f]+$", stripped) and result:
            result[-1][1] += stripped
    return result


def xwing_vectors():
    text = lines("xwing-11.txt")
    start = next(i for i, l in enumerate(text) if l.startswith("Appendix C."))
    end = next(i for i, l in enumerate(text) if l.startswith("Appendix D."))
    vectors, current = [], {}
    for label, value in fields(text[start + 2:end]):
        if label == "seed" and current:
            vectors.append(current)
            current = {}
        current[label] = value
    vectors.append(current)
    return vectors


def hpke_a5():
    text = lines("hpke-pq-05.txt")
    start = next(i for i, l in enumerate(text) if l.startswith("A.5.  MLKEM768-X25519"))
    end = next(i for i, l in enumerate(text) if l.startswith("A.6. "))
    setup, encryptions, exports = {}, [], []
    block = text[start:end]
    enc_start = next(i for i, l in enumerate(block) if l.startswith("A.5.1.1."))
    exp_start = next(i for i, l in enumerate(block) if l.startswith("A.5.1.2."))
    for label, value in fields(block[1:enc_start]):
        setup[label] = value
    current = {}
    for label, value in fields(block[enc_start + 1:exp_start]):
        if label == "sequence":
            continue
        if label == "pt" and current:
            encryptions.append(current)
            current = {}
        current[label] = value
    encryptions.append(current)
    current = {}
    for label, value in fields(block[exp_start + 1:]):
        if label == "exporter_context" and current:
            exports.append(current)
            current = {}
        current[label] = value
    exports.append(current)
    return setup, encryptions, exports


def kotlin_string(value):
    chunks = [value[i:i + 96] for i in range(0, len(value), 96)] or [""]
    return " +\n            ".join(f'"{chunk}"' for chunk in chunks)


def main():
    xwing = xwing_vectors()
    setup, encryptions, exports = hpke_a5()
    assert len(xwing) == 3 and all(len(v["pk"]) == 2432 and len(v["ct"]) == 2240 for v in xwing), "X-Wing parse"
    assert len(encryptions) == 10 and len(exports) == 5, "HPKE parse"
    out = [
        "// Generated by vectors/extract.py from draft-connolly-cfrg-xwing-kem-11 Appendix C and",
        "// draft-ietf-hpke-pq-05 Appendix A.5. Do not edit.",
        "package ch.trancee.meshlink.bench.crypto",
        "",
        "internal class XWingVector(val seed: String, val publicKey: String, val encapsSeed: String, val ciphertext: String, val sharedSecret: String)",
        "",
        "internal class HpkeEncryptionVector(val plaintext: String, val aad: String, val nonce: String, val ciphertext: String)",
        "",
        "internal class HpkeExportVector(val context: String, val length: Int, val value: String)",
        "",
        "internal object Vectors {",
        "    val xwing: List<XWingVector> = listOf(",
    ]
    for v in xwing:
        out.append("        XWingVector(")
        for key in ("seed", "pk", "eseed", "ct", "ss"):
            out.append(f"            {kotlin_string(v[key])},")
        out.append("        ),")
    out.append("    )")
    out.append("")
    for key, name in (("info", "hpkeInfo"), ("ikmE", "hpkeIkmE"), ("ikmR", "hpkeIkmR"), ("pkRm", "hpkePkRm"),
                      ("skRm", "hpkeSkRm"), ("enc", "hpkeEnc"), ("shared_secret", "hpkeSharedSecret"),
                      ("key", "hpkeKey"), ("base_nonce", "hpkeBaseNonce"), ("exporter_secret", "hpkeExporterSecret")):
        out.append(f"    const val {name}: String =\n            {kotlin_string(setup[key])}")
    out.append("    val hpkeEncryptions: List<HpkeEncryptionVector> = listOf(")
    for e in encryptions:
        out.append(f"        HpkeEncryptionVector({kotlin_string(e['pt'])}, \"{e['aad']}\", \"{e['nonce']}\", {kotlin_string(e['ct'])}),")
    out.append("    )")
    out.append("    val hpkeExports: List<HpkeExportVector> = listOf(")
    for e in exports:
        out.append(f"        HpkeExportVector(\"{e['exporter_context']}\", {e['L']}, \"{e['exported_value']}\"),")
    out.append("    )")
    out.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT}: {len(xwing)} X-Wing, {len(encryptions)} encryptions, {len(exports)} exports")


if __name__ == "__main__":
    main()
